#!/usr/bin/env python3
"""
Prime Mesh R2Q - H-Exc T_J grid extraction audit.

Extracts the sampled grid rule used by the H-Exc/SR11 bridge path exports.
"""

from __future__ import annotations

import csv
import math
import time
from collections import Counter
from pathlib import Path
from typing import Dict, Iterable, List

import numpy as np
import pandas as pd


OUT_DIR = Path(__file__).resolve().parent
P0 = 500_000_000


def geometric_h_values(max_h: int, max_points: int = 36) -> List[int]:
    max_h = int(max_h)
    vals = {1, 2, 3, 4, 5, 8, 10, 16, 32, 64, 128}
    if max_h > 1:
        for v in np.geomspace(1, max_h, num=max_points):
            vals.add(int(round(v)))
    vals.add(max_h)
    return sorted(v for v in vals if 1 <= v <= max_h)


def write_csv(path: Path, rows: List[Dict[str, object]]) -> None:
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    keys: List[str] = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                keys.append(key)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        writer.writerows(rows)


def boolish(x) -> bool:
    if isinstance(x, (bool, np.bool_)):
        return bool(x)
    if pd.isna(x):
        return False
    if isinstance(x, (int, float, np.integer, np.floating)):
        return bool(x)
    return str(x).strip().lower() in {"true", "1", "yes", "y"}


def nearest_distances(points: np.ndarray, anchors: np.ndarray) -> np.ndarray:
    if len(points) == 0:
        return np.array([], dtype=np.float64)
    if len(anchors) == 0:
        return np.full(len(points), np.nan, dtype=np.float64)
    idx = np.searchsorted(anchors, points)
    left = np.where(idx > 0, anchors[np.maximum(idx - 1, 0)], anchors[0])
    right = np.where(idx < len(anchors), anchors[np.minimum(idx, len(anchors) - 1)], anchors[-1])
    return np.minimum(np.abs(points - left), np.abs(points - right)).astype(float)


def update_manifest(paths: Iterable[Path]) -> None:
    manifest = OUT_DIR / "deposit_manifest.csv"
    existing = pd.read_csv(manifest) if manifest.exists() else pd.DataFrame()
    rows = [] if existing.empty else existing.to_dict("records")
    by_name = {str(r.get("filename")): i for i, r in enumerate(rows)}
    now = time.strftime("%Y-%m-%dT%H:%M:%S")
    for path in paths:
        rec = {
            "filename": path.name,
            "path": str(path),
            "bytes": path.stat().st_size if path.exists() else 0,
            "status": "new",
            "updated_at": now,
            "note": "H-Exc T_J grid extraction audit output",
        }
        if path.name in by_name:
            rows[by_name[path.name]] = rec
        else:
            rows.append(rec)
    write_csv(manifest, rows)


def offset_string(offsets: List[int]) -> str:
    s = ",".join(str(x) for x in offsets)
    return s if len(s) <= 600 else s[:600] + "...truncated"


